import type { Path } from "@/data/types";
import { registerTags, type Tag } from "@/data/tags";

export type ExtraSimple = {
  title: string;
  line: string;
  also: string;
  marks: string;
  exam: string;
  job: string;
  words: string;
};

const now = (a: string[], b: string[], c: string[], d: string[]): Path["now"] => ({
  "11": a,
  "12": b,
  result: c,
  college: d,
});

type Built = { path: Path; simple: ExtraSimple; tag: Tag };

export function course(input: {
  slug: string;
  name: string;
  title: string;
  line: string;
  also: string;
  marks: string;
  examText: string;
  job: string;
  words: string;
  tag: Tag;
  maths: Path["maths"];
  duration: string;
  cost: Path["cost"];
  costNote: string;
  class11: string;
  class12: string;
  gates: Path["gates"];
  examName: string;
  examWhen: string;
  examPapers: string;
  how: string[];
  places: Path["places"];
  watch: string[];
  careers: string[];
  pair: string[];
  delhi: string;
  firstPay: string;
  group: Path["group"];
  steps: [string[], string[], string[], string[]];
}): Built {
  const { tag, title, line, also, marks, examText, job, words, steps, ...rest } = input;
  return {
    tag,
    simple: { title, line, also, marks, exam: examText, job, words },
    path: {
      slug: rest.slug,
      name: rest.name,
      kicker: title,
      group: rest.group,
      oneLine: line,
      maths: rest.maths,
      duration: rest.duration,
      cost: rest.cost,
      costNote: rest.costNote,
      class11: rest.class11,
      class12: rest.class12,
      gates: rest.gates,
      exams: [{ name: rest.examName, when: rest.examWhen, papers: rest.examPapers }],
      how: rest.how,
      placesLabel: "Places worth naming",
      places: rest.places,
      after: [
        { when: "First years", what: job, money: rest.firstPay },
        { when: "Later", what: rest.careers.join(", ") + ".", money: "The first salary is not the career." },
      ],
      careers: rest.careers,
      pair: rest.pair,
      watch: rest.watch,
      now: now(...steps),
      delhi: rest.delhi,
      bestIf: tag.goodFor,
      firstPay: rest.firstPay,
    },
  };
}

